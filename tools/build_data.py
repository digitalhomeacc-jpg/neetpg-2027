"""Turn the extracted sheet JSON into js/data-wor.js for the app.

Usage: python3 tools/extract_sheet.py EXAM_PREP.xlsx wor.json
       python3 tools/build_data.py wor.json js/data-wor.js
"""
import json, sys
d = json.load(open(sys.argv[1]))
# Rows with no runtime are reminders in the sheet, not videos.
d['videos'] = [v for v in d['videos'] if v['mins'] > 0]
for v in d['videos']:
    v['mins'] = round(v['mins'], 1)
    v['done'] = v.pop('passes')
    v.pop('date', None)
# Runtimes checked against the Marrow app where the sheet was off.
RUNTIME_FIX = {'wor-ophtha-03': 65, 'wor-pathol-13': 67}
for v in d['videos']:
    if v.get('id') in RUNTIME_FIX: v['mins'] = float(RUNTIME_FIX[v['id']])
d['source'] = 'Marrow WOR'
d['sheetDoneDate'] = '2026-11-19'
with open(sys.argv[2], 'w') as f:
    f.write('// Generated by tools/build_data.py from the EXAM_PREP sheet. Edit the sheet or the script, not this file.\n')
    f.write('window.WOR = ' + json.dumps(d, ensure_ascii=False, separators=(',', ':')) + ';\n')
print(len(d['videos']), 'videos written')
